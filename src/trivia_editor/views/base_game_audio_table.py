from PySide6.QtCore import Qt, Signal
from PySide6.QtGui import QColor
from PySide6.QtWidgets import(
  QLabel, QPushButton,
  QVBoxLayout, QHBoxLayout, QStackedLayout,
  QWidget,
  QTableWidget, QTableWidgetItem, QComboBox,
  QFileDialog, QMessageBox
)

from trivia_editor.models.basic_question import Question

class BaseGameAudioTable(QWidget):
  HEADERS = [
    "ID",
    "Question",
    "Question subtitle",
    # "Question audio",
    "Intro subtitle",
    # "Intro audio",
    "Outro subtitle",
    # "Outro audio",
  ]

  def __init__(self, parent=None):
    super().__init__(parent)

    # because there can't be a widget without a layout...
    layout = QVBoxLayout(self)

    self.table = QTableWidget(0, len(self.HEADERS), self)
    self.table.setHorizontalHeaderLabels(self.HEADERS)
    self.table.verticalHeader().hide() #hide autogenerated IDs
    layout.addWidget(self.table)

  def refresh(self, questions: list[Question]):
    # remove all existing entries
    self.table.setRowCount(0)

    for q in questions:
      this_row = self.table.rowCount()
      self.table.insertRow(this_row)

      ###########
      ########### CHANGE THIS LATER
      ###########
      values = [
        q.id,
        q.text,
        q.questionAudio,
        q.introAudio,
        q.outro,
      ]

      for col_nr, value in enumerate(values):
        cell = QTableWidgetItem(str(value))
        if col_nr < 2: # making ID & question columns not editable
          cell.setFlags(cell.flags() & ~Qt.ItemIsEditable)
        self.table.setItem(this_row, col_nr, cell)
      ###########
      ########### CHANGE THIS LATER
      ###########

  def highlight_errors(self, errors: dict[int, list[str]]):
    for row in range(self.table.rowCount()):
      # ALWAYS clear previous highlights
      for column in range(self.table.columnCount()):
        item = self.table.item(row, column)
        if item is not None:
          item.setBackground(QColor())
          item.setToolTip("")
      # check if this row has an error msg
      q_id = int(self.table.item(row,0).text())
      if not q_id in errors:
        continue
      # this has an error; mark it
      error_msg = "\n".join(errors[q_id])
      for column in range(self.table.columnCount()):
        item = self.table.item(row, column)
        if item is not None:
          item.setBackground(self.ERROR_HIGHLIGHT)
          # we don't have a good way of checking what cell this is,
          # so set the same tooltip for everything
          item.setToolTip(error_msg)

