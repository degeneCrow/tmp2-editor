from PySide6.QtCore import Qt, Signal
from PySide6.QtGui import QColor
from PySide6.QtWidgets import(
  QLabel, QPushButton,
  QVBoxLayout, QHBoxLayout, QStackedLayout,
  QWidget,
  QTableWidget, QTableWidgetItem, QComboBox,
  QFileDialog, QMessageBox
)

from trivia_editor.models.basic_question import Question,Choice

class BaseQuestionsView(QWidget):
  HEADERS = [
    "ID",
    "Question",
    "Choice 1",
    "Choice 2",
    "Choice 3",
    "Choice 4",
    "Correct choice",
  ]

  s_load_active = Signal()
  s_load_custom = Signal(str)
  s_save_active = Signal()
  s_save_custom = Signal(str)
  s_add_question = Signal()
  s_del_question = Signal(int)

  TC_BUTTONS = [
    (
      "Load active question set",
      "Read the question database that the game would load if you ran it now",
      "s_load_active"
    ),
    (
      "Load question set...",
      "Pick the question database to edit (make sure it's for the base game!)",
      "_choose_custom_db_to_load"
    ),
    (
      "Save as Active",
      "Save the current question database as the one the game would load if you ran it now",
      "s_save_active"
    ),
    (
      "Save as...",
      "Save the current question database with a custom name; useful for testing and iteration",
      "_choose_custom_db_to_save"
    ),
    (
      "Add question",
      "Insert a new row of questions at the end of the database",
      "s_add_question"
    ),
    (
      "Delete question",
      "Remove the selected question from the database",
      "_remove_selected_question"
    ),
  ]

  ERROR_HIGHLIGHT = QColor('#dd6969')

  def __init__(self, parent=None):
    super().__init__(parent)

    # main container for the temp text AND table & controls
    self.pages = QStackedLayout(self)

    # Placeholder content page
    self.placeholder_page = QWidget()
    p_layout = QVBoxLayout(self.placeholder_page)
    p_layout.addWidget(
      QLabel("Select game folder to load questions!")
    )
    # adding page to main layout
    self.pages.addWidget(self.placeholder_page)

    # main content page
    self.content_page = QWidget()
    c_layout = QHBoxLayout(self.content_page)

    self.table = QTableWidget(0, len(self.HEADERS), self)
    self.table.setHorizontalHeaderLabels(self.HEADERS)
    self.table.verticalHeader().hide() #hide autogenerated IDs
    c_layout.addWidget(self.table)

    self.table_controls = QWidget()
    tc_layout = QVBoxLayout(self.table_controls)
    tc_layout.setAlignment(Qt.AlignmentFlag.AlignTop)
    for text, tooltip, signal_name in self.TC_BUTTONS:
      button = QPushButton(text)
      button.setToolTip(tooltip)
      button.clicked.connect(getattr(self, signal_name))
      tc_layout.addWidget(button)
    c_layout.addWidget(self.table_controls)

    # adding page to main layout
    self.pages.addWidget(self.content_page)

  def _refresh_questions(self, questions: list[Question]):
    self.table.blockSignals(True)
    self.table.setRowCount(0)

    for question in questions:
      # calculating temp id of "correct answer"
      correct_answers = [
        index + 1
        for index, choice in enumerate(question.choices)
        if choice.correct
      ]
      the_answer = correct_answers[0] if correct_answers else 0

      choices = [c.text for c in question.choices]
      choices.extend([""] * (4 - len(choices)))

      this_row = self.table.rowCount()
      self.table.insertRow(this_row)

      values = [
        question.id,
        question.text,
        *choices,
      ]

      for column, value in enumerate(values):
        cell = QTableWidgetItem(str(value))
        # making ID column not editable
        if column == 0:
          cell.setFlags(cell.flags() & ~Qt.ItemIsEditable)
        self.table.setItem(this_row, column, cell)

      correct_cb = QComboBox()
      correct_cb.addItems(["0", "1", "2", "3", "4"])
      cb_model = correct_cb.model()
      cb_model.item(0).setEnabled(False)
      correct_cb.setCurrentIndex(the_answer)
      correct_cb.currentIndexChanged.connect(
        lambda _index, row=this_row: self._on_correct_choice_changed(this_row)
      )
      self.table.setCellWidget(this_row, 6, correct_cb)

    self.table.resizeColumnsToContents()
    self.table.blockSignals(False)
    self.table.show()

  def highlight_error_rows(self, errors: dict[int, list[str]]):
    print("error highlighting called")
    for row in range(self.table.rowCount()):
      # ALWAYS clear previous highlights
      for column in range(self.table.columnCount()):
        item = self.table.item(row, column)
        if item is not None:
          item.setBackground(QColor())
          item.setToolTip("")
      # check if this row has an error msg
      q_id = int(self.table.item(row,0).text())
      if not q_id in errors:
        continue
      # this has an error; mark it
      error_msg = "\n".join(errors[q_id])
      for column in range(self.table.columnCount()):
        item = self.table.item(row, column)
        if item is not None:
          item.setBackground(self.ERROR_HIGHLIGHT)
          # we don't have a good way of checking what cell this is,
          # so set the same tooltip for everything
          item.setToolTip(error_msg)

    QMessageBox.warning(
        self,
        "Question errors!",
        f"The following questions have errors:\n - {"\n - ".join(str(q_id) for q_id in errors)}"
    )

  # a tiny helper method to link combobox edit to table edit
  def _on_correct_choice_changed(self, row: int):
    # this is bad but eeeeeeeeeh
    cell = self.table.item(row, 1)
    self.table.itemChanged.emit(cell)

  def _display_questions(self, questions: list[Question]):
    self.pages.setCurrentWidget(self.placeholder_page)
    self._refresh_questions(questions)
    self.pages.setCurrentWidget(self.content_page)

  def _choose_custom_db_to_load(self):
    path, _ = QFileDialog.getOpenFileName(
      self,
      "Load question database",
      "",
      "Trivia Murder Party Question databases (*.jet);;All files (*)",
    )
    if path:  # Empty when cancelled
      self.s_load_custom.emit(path)

  def _choose_custom_db_to_save(self):
    path, _ = QFileDialog.getSaveFileName(
      self,
      "Save question database",
      "",
      "Trivia Murder Party Question databases (*.jet)",
    )
    if path:  # Empty when cancelled
      #making sure the right extension is set
      if not path.lower().endswith(".jet"):
        path += ".jet"
      self.s_save_custom.emit(path)

  def _remove_selected_question(self):
    r_id = self.table.currentRow()
    if r_id < 0:
      return

    q_id_cell = self.table.item(r_id, 0)
    q_id = int(q_id_cell.text()) # the ID of the question in the database
    self.s_del_question.emit(q_id)
